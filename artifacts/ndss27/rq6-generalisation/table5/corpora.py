"""Per-ISA instruction corpora for mt_multiarch.py / campaign_bits.py.

Each CORPORA[key](isa) -> list of (label, code_spec, src_regs[, constraints]):
  * keystone ISAs: code_spec = assembly string
  * riscv:         code_spec = hex machine code (no keystone for RISC-V)
  * src_regs   = registers the instruction READS and that may be tainted (GPRs
                 and/or flags); ALL GPRs+flags are checked as outputs regardless.
  * constraints = optional {reg: 'nonzero'}, pinning a register out of an
                 undefined domain for the WHOLE 2^k enumeration (a divisor must
                 be non-zero at every point of the cube, not just the base case,
                 or Unicorn traps mid-oracle).

Coverage goals, in rough order of how much they have caught:

  1. INSTRUCTION SHAPE.  Every real engine bug this session came from a shape not
     previously exercised (ARM64's shifted-register operand, MIPS `mul`'s
     truncate-then-sign-extend, RISC-V's computed shift mask).  So the corpora
     aim for shape variety -- widening, narrowing, extended-register operands,
     rotate-and-mask, multiply-accumulate, bit tests -- rather than long lists of
     near-identical mnemonics.
  2. FLAG PRODUCERS AND CONSUMERS.  adds/subs/cmp/tst produce; adc/sbc/cset/csel
     consume; ccmp both.
  3. OPERAND WIDTH.  32-bit forms on 64-bit ISAs, and x86's 32/16/8-bit
     sub-register writes, where a narrow write must preserve the upper bits'
     taint.
  4. MULTI-OUTPUT.  x86 `mul` writes RDX:RAX.

Known remaining gap: no LOAD/STORE anywhere, so the shadow-memory path and
address-taint handling are unexercised.  That needs memory support in the oracle
(seeding and reading a data page, plus threading memory taint into the worker),
which is a harness change rather than a corpus one.
"""


