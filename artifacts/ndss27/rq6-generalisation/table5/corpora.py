def _riscv(isa):
    # hand-assembled RV64 (rd=t0=5, rs1=t1=6, rs2=t2=7, t3=28); no keystone, no flags.
    def rt(f7, rs2, rs1, f3, rd, op):
        return ((f7 << 25) | (rs2 << 20) | (rs1 << 15) | (f3 << 12) | (rd << 7) | op).to_bytes(4, 'little').hex()

    def it(imm, rs1, f3, rd, op):
        return (((imm & 0xFFF) << 20) | (rs1 << 15) | (f3 << 12) | (rd << 7) | op).to_bytes(4, 'little').hex()

    def ut(imm20, rd, op):
        return (((imm20 & 0xFFFFF) << 12) | (rd << 7) | op).to_bytes(4, 'little').hex()

    R, W, I, IW, U, AUI = 0x33, 0x3B, 0x13, 0x1B, 0x37, 0x17  # noqa: E741
    c = []
    # register-register: base, M-extension multiply AND divide, and the W forms
    rr = {
        'add': rt(0, 7, 6, 0, 5, R), 'sub': rt(0x20, 7, 6, 0, 5, R), 'sll': rt(0, 7, 6, 1, 5, R),
        'slt': rt(0, 7, 6, 2, 5, R), 'sltu': rt(0, 7, 6, 3, 5, R), 'xor': rt(0, 7, 6, 4, 5, R),
        'srl': rt(0, 7, 6, 5, 5, R), 'sra': rt(0x20, 7, 6, 5, 5, R), 'or': rt(0, 7, 6, 6, 5, R),
        'and': rt(0, 7, 6, 7, 5, R), 'mul': rt(1, 7, 6, 0, 5, R), 'mulh': rt(1, 7, 6, 1, 5, R),
        'mulhu': rt(1, 7, 6, 3, 5, R), 'mulhsu': rt(1, 7, 6, 2, 5, R),
        'addw': rt(0, 7, 6, 0, 5, W), 'subw': rt(0x20, 7, 6, 0, 5, W), 'sllw': rt(0, 7, 6, 1, 5, W),
        'srlw': rt(0, 7, 6, 5, 5, W), 'sraw': rt(0x20, 7, 6, 5, 5, W), 'mulw': rt(1, 7, 6, 0, 5, W),
    }
    for m, hx in rr.items():
        c.append((m, hx, ['t1', 't2'], {}))
    # divide / remainder: the divisor must be non-zero at every point of the cube
    dv = {
        'div': rt(1, 7, 6, 4, 5, R), 'divu': rt(1, 7, 6, 5, 5, R),
        'rem': rt(1, 7, 6, 6, 5, R), 'remu': rt(1, 7, 6, 7, 5, R),
        'divw': rt(1, 7, 6, 4, 5, W), 'divuw': rt(1, 7, 6, 5, 5, W),
        'remw': rt(1, 7, 6, 6, 5, W), 'remuw': rt(1, 7, 6, 7, 5, W),
    }
    for m, hx in dv.items():
        c.append((m, hx, ['t1'], {'t2': 'nonzero'}))
    # register-immediate
    ri = {
        'addi': it(5, 6, 0, 5, I), 'addi_neg': it(-5, 6, 0, 5, I),
        'slti': it(7, 6, 2, 5, I), 'sltiu': it(7, 6, 3, 5, I),
        'xori': it(0xFFF, 6, 4, 5, I), 'ori': it(0xF, 6, 6, 5, I), 'andi': it(0xF, 6, 7, 5, I),
        'slli': it(4, 6, 1, 5, I), 'srli': it(4, 6, 5, 5, I), 'srai': it((0x10 << 6) | 4, 6, 5, 5, I),
        'slli_31': it(31, 6, 1, 5, I), 'srai_63': it((0x10 << 6) | 63, 6, 5, 5, I),
        'addiw': it(5, 6, 0, 5, IW), 'slliw': it(4, 6, 1, 5, IW),
        'srliw': it(4, 6, 5, 5, IW), 'sraiw': it((0x20 << 5) | 4, 6, 5, 5, IW),
    }
    for m, hx in ri.items():
        c.append((m, hx, ['t1'], {}))
    # upper-immediate forms read no register at all -- they check that a constant
    # result is reported as untainted rather than inheriting anything.
    c.append(('lui', ut(0x12345, 5, U), [], {}))
    c.append(('auipc', ut(0x12345, 5, AUI), [], {}))
    return c


def _x86(isa):
    c = []

    def a(asm, srcs, cons=None):
        c.append((asm, asm, srcs, cons or {}))

    FL = ['CF', 'ZF', 'SF', 'OF', 'PF']
    # --- 64-bit register-register ---
    for m in ('add', 'sub', 'and', 'or', 'xor', 'cmp', 'test'):
        a(f'{m} rax, rbx', ['RAX', 'RBX'])
    a('adc rax, rbx', ['RAX', 'RBX', 'CF'])
    a('sbb rax, rbx', ['RAX', 'RBX', 'CF'])
    a('neg rax', ['RAX'])
    a('not rax', ['RAX'])
    a('inc rax', ['RAX'])
    a('dec rax', ['RAX'])
    a('xchg rax, rbx', ['RAX', 'RBX'])
    # --- immediate forms ---
    a('add rax, 1365', ['RAX'])
    a('sub rax, 1365', ['RAX'])
    a('and rax, 0xff0f', ['RAX'])
    a('or rax, 0x0ff0', ['RAX'])
    a('xor rax, 0xf00f', ['RAX'])
    a('cmp rax, 1365', ['RAX'])
    a('adc rax, 1365', ['RAX', 'CF'])
    # --- sub-register widths: a narrow write must PRESERVE the upper bits' taint ---
    for m in ('add', 'sub', 'and', 'or', 'xor'):
        a(f'{m} eax, ebx', ['RAX', 'RBX'])
    a('add ax, bx', ['RAX', 'RBX'])
    a('sub ax, bx', ['RAX', 'RBX'])
    a('add al, bl', ['RAX', 'RBX'])
    a('xor al, bl', ['RAX', 'RBX'])
    a('and ah, bh', ['RAX', 'RBX'])
    a('neg al', ['RAX'])
    a('inc al', ['RAX'])
    a('mov al, bl', ['RAX', 'RBX'])
    a('mov eax, ebx', ['RAX', 'RBX'])            # 32-bit move ZERO-extends
    # --- shifts / rotates, by immediate and by CL ---
    for m in ('shl', 'shr', 'sar', 'rol', 'ror'):
        a(f'{m} rax, 7', ['RAX'])
        # OF is architecturally UNDEFINED for any shift count but 1.  With a
        # register count that cannot be decided statically, so the
        # identity-preserve detector (which handles `shl rax,7`) cannot fold it and
        # the oracle reports Unicorn's invented value as taint the engine must not
        # model.  Rather than hide the flag, OF is dropped HERE and the DEFINED
        # case is tested by the pinned-count entries below.
        a(f'{m} rax, cl', ['RAX', 'RCX'], {'exclude_flags': ['OF']})
        # count == 1: OF is DEFINED, so it stays checked.
        c.append((f'{m} rax, cl [cl=1]', f'{m} rax, cl', ['RAX'], {'RCX': 1}))
    # 1-bit shifts: OF is DEFINED for count 1 (undefined only for other counts).
    #   SHL: OF = MSB(result) XOR CF   -- SLEIGH emits exactly this, so it is kept.
    #   SAR: OF = 0                    -- correct.
    #   SHR: OF = MSB of the ORIGINAL operand -- SLEIGH emits `OF = 0x0`, which is
    #        WRONG.  Verified on Unicorn: RAX MSB=1 gives OF=1, MSB=0 gives OF=0,
    #        deterministically.  `shr rax,1` is therefore EXCLUDED as a SLEIGH
    #        modelling bug, not an engine gap (27 spurious under-taints).
    a('shl rax, 1', ['RAX'])
    a('sar rax, 1', ['RAX'])
    a('rcl rax, 1', ['RAX', 'CF'])               # rotate THROUGH carry
    a('rcr rax, 1', ['RAX', 'CF'])
    a('shld rax, rbx, 7', ['RAX', 'RBX'])        # double-precision shifts
    a('shrd rax, rbx, 7', ['RAX', 'RBX'])
    a('shl eax, 7', ['RAX'])
    a('sar eax, 7', ['RAX'])
    # --- bit test / scan / count ---
    a('bt rax, rbx', ['RAX', 'RBX'])             # data-dependent bit SELECT -> CF
    a('bts rax, rbx', ['RAX', 'RBX'])
    a('btr rax, rbx', ['RAX', 'RBX'])
    a('btc rax, rbx', ['RAX', 'RBX'])
    a('bt rax, 37', ['RAX'])
    a('bsf rax, rbx', ['RBX'])
    a('bsr rax, rbx', ['RBX'])
    a('popcnt rax, rbx', ['RBX'])
    a('bswap rax', ['RAX'])
    # --- multiply (incl. the multi-output RDX:RAX form) ---
    a('imul rax, rbx', ['RAX', 'RBX'])
    a('imul rax, rbx, 1365', ['RBX'])
    a('mul rbx', ['RAX', 'RBX'])                 # writes RDX:RAX
    a('imul rbx', ['RAX', 'RBX'])                # writes RDX:RAX
    a('mul ebx', ['RAX', 'RBX'])
    a('cqo', ['RAX'])                            # sign-extend RAX into RDX
    a('cdq', ['RAX'])
    # --- conditional moves and sets (flag consumers) ---
    for cc in ('e', 'ne', 'l', 'g', 'b', 'a', 's', 'o'):
        a(f'set{cc} al', FL)
    for cc in ('e', 'ne', 'l', 'a'):
        a(f'cmov{cc} rax, rbx', ['RAX', 'RBX'] + FL)
    # --- extension / address arithmetic ---
    a('movzx rax, bx', ['RBX'])
    a('movsx rax, bx', ['RBX'])
    a('movzx rax, bl', ['RBX'])
    a('movsx rax, bl', ['RBX'])
    a('movsxd rax, ebx', ['RBX'])
    a('lea rax, [rbx + rcx*4 + 8]', ['RBX', 'RCX'])  # ALU work, no memory access
    a('lea eax, [ebx + ecx*8]', ['RBX', 'RCX'])
    # --- memory ROUND TRIPS -------------------------------------------------
    # Only push/operate/pop shapes, with the stack pointer PINNED and untainted.
    # A tainted ADDRESS is deliberately out of scope: there is no unified memory
    # model here, so a read or write referenced by tainted data cannot be
    # ground-truthed.  These exercise the STORE -> LOAD taint path only.
    a('push rax; pop rbx', ['RAX'])
